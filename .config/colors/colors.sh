  border-radius: 10px;
  border: 2px solid #$ACCENT;
  background: rgba($BG_R, $BG_G, $BG_B, 0.87);
}

window#osd #container {
  margin: 16px;
}

window#osd image,
window#osd label {
  color: rgba($TEXT_R, $TEXT_G, $TEXT_B, 1);
}

window#osd progressbar:disabled,
window#osd image:disabled {
  opacity: 0.5;
}

window#osd progressbar,
window#osd segmentedprogress {
  min-height: 6px;
  border-radius: 999px;
  background: transparent;
  border: none;
}

window#osd trough,
window#osd segment {
  min-height: 6px;
  border-radius: 999px;
  border: none;
  background: rgba($TEXT_R, $TEXT_G, $TEXT_B, 0.5);
}

window#osd progress,
window#osd segment.active {
  min-height: 6px;
  border-radius: 999px;
  border: none;
  background: rgba($TEXT_R, $TEXT_G, $TEXT_B, 1);
}

window#osd segment {
  margin-left: 8px;
}

window#osd segment:first-child {
  margin-left: 0;
}
CSSEOF

mkdir -p ~/.config/swaync
cat > ~/.config/swaync/style.css << CSSEOF
