#!/bin/bash
# One source of truth — edit the 5 hex values below, then run ./colors.sh

BACKGROUND="2a2d2a"
TEXT="a1b5a1"
ACCENT="a1b5a1"
INACTIVE="353b35"
URGENT="cbe25a"

DIR="$(cd "$(dirname "$0")" && pwd)"

BG_R=$((16#${BACKGROUND:0:2}))
BG_G=$((16#${BACKGROUND:2:2}))
BG_B=$((16#${BACKGROUND:4:2}))

TEXT_R=$((16#${TEXT:0:2}))
TEXT_G=$((16#${TEXT:2:2}))
TEXT_B=$((16#${TEXT:4:2}))

INACTIVE_R=$((16#${INACTIVE:0:2}))
INACTIVE_G=$((16#${INACTIVE:2:2}))
INACTIVE_B=$((16#${INACTIVE:4:2}))

BR_INACTIVE="$INACTIVE_R, $INACTIVE_G, $INACTIVE_B"

# SURFACE: BACKGROUND lightened 10% toward white (Waybar module backgrounds)
SURFACE_R=$(( BG_R + (255 - BG_R) / 10 ))
SURFACE_G=$(( BG_G + (255 - BG_G) / 10 ))
SURFACE_B=$(( BG_B + (255 - BG_B) / 10 ))
SURFACE=$(printf '%02x%02x%02x' $SURFACE_R $SURFACE_G $SURFACE_B)

cat > "$DIR/colors.css" << EOF
@define-color background rgba($BG_R, $BG_G, $BG_B, 1.0);
@define-color text #$TEXT;
@define-color accent #$ACCENT;
@define-color inactive #$INACTIVE;
@define-color urgent #$URGENT;
@define-color surface #$SURFACE;
EOF

cat > "$DIR/colors.rasi" << EOF
* {
    bg:                          #$BACKGROUND;
    foreground-color:            #$TEXT;
    foreground-color-alt:        #$ACCENT;
    accent-color:                #$ACCENT;
    border-color:                #$ACCENT;
    on:                          #$ACCENT;
    off:                         #$INACTIVE;
    urgent:                      #$URGENT;
    surface:                     #$SURFACE;
}
EOF

cat > "$DIR/hyprland-colors.conf" << EOF
# Auto-generated from colors.sh
\$background = rgba(${BACKGROUND}ee)
\$text = rgb($TEXT)
\$accent = rgb($ACCENT)
\$inactive = rgb($INACTIVE)
\$urgent = rgb($URGENT)
EOF

cat > "$DIR/hyprland-colors.lua" << EOF
-- Auto-generated from colors.sh
return {
    background = "rgba(${BACKGROUND}ee)",
    text = "rgb($TEXT)",
    accent = "rgb($ACCENT)",
    inactive = "rgb($INACTIVE)",
    urgent = "rgb($URGENT)",
}
EOF

# Waybar calendar tooltip: Pango markup can't read @define-color, so write SURFACE in directly
sed -i -E "s|(\"today\": \"<span background='#)[0-9a-fA-F]{6}|\\1$SURFACE|" ~/.config/waybar/config

mkdir -p ~/.config/swayosd
cat > ~/.config/swayosd/style.css << CSSEOF
